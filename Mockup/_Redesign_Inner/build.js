/* Builds the draft pages: src/<name>.html → <name>.html, filling in the parts
   every page shares so they cannot drift apart.

     <!--@head title="…"-->               doctype, metas, kit.css, the before-paint mode script
     <!--@mast current="classes" wa="…"-->  masthead; `current` marks the nav item,
                                           `wa` finishes "I'd like to ask about …"
     <!--@foot-->                          footer
     <!--@scripts-->                       GSAP, ScrollTrigger, SplitText, Lenis, kit.js

   Run: node build.js        Any directive left unfilled stops the build.

   It then publishes the result to /new/ at the site root, the live test URL
   (shaheedibunga.com/new/): the built pages, kit.css, kit.js, lib/ and img/.
   /new/ is generated - never edit it; _tools/check-generated.sh fails if it
   differs from what this produces. */
const fs = require('fs'), path = require('path');
const here = __dirname, SRC = path.join(here, 'src'), PART = path.join(here, 'partials');
const part = n => fs.readFileSync(path.join(PART, n), 'utf8');
const attrs = s => Object.fromEntries([...s.matchAll(/(\w+)="([^"]*)"/g)].map(m => [m[1], m[2]]));
const esc = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');

const NAV = [['classes', 'Classes'], ['resources', 'Resources'], ['gallery', 'Gallery'],
             ['about', 'About'], ['contact', 'Contact'], ['donate', 'Donate']];

function mast(a){
  const nav = NAV.map(([k, label]) =>
    `<a href="${k}.html"${k === a.current ? ' aria-current="page"' : ''}>${label}</a>`).join('');
  const text = encodeURIComponent(`Sat Sri Akal — I'd like to ask about ${a.wa || 'classes'}.`);
  return part('mast.html').replace('{{nav}}', nav).replace('{{wa}}', `https://wa.me/447394848407?text=${text}`);
}

let built = 0;
for (const f of fs.readdirSync(SRC).filter(f => f.endsWith('.html'))) {
  let h = fs.readFileSync(path.join(SRC, f), 'utf8');
  h = h.replace(/<!--@head([^>]*)-->/, (_, a) => part('head.html').replace('{{title}}', esc(attrs(a).title || 'Shaheedi Bunga')))
       .replace(/<!--@mast([^>]*)-->/, (_, a) => mast(attrs(a)))
       .replace(/<!--@foot-->/, () => part('foot.html'))
       .replace(/<!--@scripts-->/, () => part('scripts.html'));
  const left = h.match(/<!--@\w+/);
  if (left) throw new Error(`${f}: ${left[0]} was not filled in`);
  fs.writeFileSync(path.join(here, f), h);
  built++;
}
console.log(`built ${built} pages`);

const OUT = path.resolve(here, '../../new');
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const pages = fs.readdirSync(here).filter(f => f.endsWith('.html'));
for (const f of [...pages, 'kit.css', 'kit.js']) fs.copyFileSync(path.join(here, f), path.join(OUT, f));
for (const d of ['lib', 'img']) fs.cpSync(path.join(here, d), path.join(OUT, d), { recursive: true, filter: s => !s.endsWith('.DS_Store') });
fs.writeFileSync(path.join(OUT, 'README.md'),
  '# /new/: the redesign test URL\n\nGenerated by `Mockup/_Redesign_Inner/build.js`. Do not edit anything here:\n' +
  'edit `Mockup/_Redesign_Inner/src/` and run `node Mockup/_Redesign_Inner/build.js`.\n');
console.log(`published ${pages.length} pages to /new/`);
